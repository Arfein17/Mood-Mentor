// ── Fallback Mocks (if no API key provided) ──

function mockAnalyzeCheckin(text, userEmotion) {
  console.log('[Gemini] Using advanced local mock for analyzeCheckin.');
  const emotion = userEmotion || 'Calm';
  
  // Simple deterministic hash based on text length and character codes
  let hash = 0;
  if (text) {
    for (let i = 0; i < text.length; i++) {
      hash = ((hash << 5) - hash) + text.charCodeAt(i);
      hash = hash & hash;
    }
  }
  const pseudoRandom = Math.abs(hash) / 2147483647; // 0 to 1

  // Create a realistic looking fake distribution
  const distribution = {};
  WELLNESS_CLASSES.forEach(c => distribution[c] = 0.05);
  distribution[emotion] = 0.75;
  
  const scoreMap = { 'Happy': 90, 'Calm': 80, 'Stressed': 35, 'Anxious': 30, 'Frustrated': 25, 'Sad': 20 };
  let wellnessScore = scoreMap[emotion] || 50;

  // Modulate based on text length using pseudoRandom
  if (text && text.length > 20) {
    wellnessScore += (pseudoRandom * 10 - 5);
  }
  
  // Return realistic dynamic confidence instead of locked 55%
  const confidence = 0.70 + (pseudoRandom * 0.25); // 70% to 95%

  return {
    dominantEmotion: emotion,
    wellnessScore: Math.round(Math.max(0, Math.min(100, wellnessScore))),
    confidence: Math.round(confidence * 100) / 100,
    distribution,
    signals: { text: !!text, face: false, selfReport: !!userEmotion },
    disclaimer: 'This is a simulated AI analysis.'
  };
}

