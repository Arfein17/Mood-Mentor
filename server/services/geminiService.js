const { GoogleGenAI } = require('@google/genai');

let ai;
try {
  // Initialize only if key is available
  if (process.env.GEMINI_API_KEY) {
    ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
  }
} catch (err) {
  console.log('[Gemini] Not initialized. Fallback mode will be used.');
}

const WELLNESS_CLASSES = ['Happy', 'Calm', 'Stressed', 'Anxious', 'Frustrated', 'Sad'];

/**
 * Analyzes the user check-in using Gemini.
 * Returns { dominantEmotion, wellnessScore, confidence, distribution, disclaimer }
 */
async function analyzeCheckin(text, userEmotion, imageBuffer) {
  if (!ai) {
    return mockAnalyzeCheckin(text, userEmotion);
  }

  try {
    const prompt = `
      You are an expert psychological sentiment analyzer for a wellness app.
      Analyze the following check-in data from a user.
      User explicitly selected emotion emoji: ${userEmotion || 'None'}
      User written text: "${text || 'None'}"
      ${imageBuffer ? 'The user also provided a selfie.' : ''}

      Based on this data, output a JSON object exactly in this format (no markdown tags, just pure JSON):
      {
        "dominantEmotion": "One of: Happy, Calm, Stressed, Anxious, Frustrated, Sad",
        "wellnessScore": <integer from 0 to 100 representing overall wellness, 100 being perfect>,
        "confidence": <float between 0.0 and 1.0 representing your confidence in this analysis>,
        "distribution": {
           "Happy": <float 0-1>,
           "Calm": <float 0-1>,
           "Stressed": <float 0-1>,
           "Anxious": <float 0-1>,
           "Frustrated": <float 0-1>,
           "Sad": <float 0-1>
        }
      }
      The distribution values must sum to 1.0.
    `;

    // Note: We are ignoring the imageBuffer for the API call to keep it fast and simple, 
    // but the prompt is aware if they provided one.
    
    const modelName = 'gemini-3.6-flash';
    let response;
    try {
      response = await ai.models.generateContent({
        model: modelName,
        contents: prompt,
        config: {
          responseMimeType: "application/json",
        }
      });
    } catch (modelErr) {
      console.warn(`[Gemini] ${modelName} failed, attempting gemini-flash-latest fallback:`, modelErr.message);
      response = await ai.models.generateContent({
        model: 'gemini-flash-latest',
        contents: prompt,
        config: {
          responseMimeType: "application/json",
        }
      });
    }

    const result = JSON.parse(response.text);
    return {
      dominantEmotion: result.dominantEmotion,
      wellnessScore: result.wellnessScore,
      confidence: result.confidence,
      distribution: result.distribution,
      signals: { text: !!text, face: !!imageBuffer, selfReport: !!userEmotion },
      disclaimer: 'This analysis was generated by AI and is not a medical diagnosis.'
    };
  } catch (err) {
    console.error('[Gemini] API error, falling back to mock:', err);
    return mockAnalyzeCheckin(text, userEmotion);
  }
}

